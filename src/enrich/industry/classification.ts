/** 中分類コード → 大分類の記号。 */
export function majorDivisionOf(code: string): string | null {
  const n = Number.parseInt(code, 10);
  if (Number.isNaN(n)) return null;
  if (n <= 2) return 'A';
  if (n === 3 || n === 4) return 'B';
  if (n === 5) return 'C';
  if (n <= 8) return 'D';
  if (n <= 32) return 'E';
  if (n <= 36) return 'F';
  if (n <= 41) return 'G';
  if (n <= 49) return 'H';
  if (n <= 61) return 'I';
  if (n <= 67) return 'J';
  if (n <= 70) return 'K';
  if (n <= 74) return 'L';
  if (n <= 77) return 'M';
  if (n <= 80) return 'N';
  if (n <= 82) return 'O';
  if (n <= 85) return 'P';
  if (n <= 87) return 'Q';
  if (n <= 95) return 'R';
  if (n <= 98) return 'S';
  return 'T';
}

/** 中分類コードの表示名。未知のコードはそのまま返す。 */
export function divisionName(code: string): string {
  return DIVISIONS[code] ?? code;
}
